// commandWorld gives commands a place to run: not /tmp, which the sandbox
// mounts fresh and empty over its own.
func commandWorld(t *testing.T) {
	t.Helper()
	world(t)
	cache, err := os.UserCacheDir()
	if err != nil {
		cache = os.Getenv("HOME")
	}
	dir, err := os.MkdirTemp(cache, "gohort-service-test-")
	if err != nil {
		t.Skip("no folder outside /tmp to run commands in")
	}
	t.Cleanup(func() { os.RemoveAll(dir) })
	flows.SetWorkBase(filepath.Join(dir, "runs"))
	if _, err := flows.RunCommand(context.Background(), flows.Command{Steps: []string{"printf ok"}}); err != nil && strings.Contains(err.Error(), "sandbox") {
		t.Skipf("no sandbox to run commands in here: %v", err)
	}
}

func commandSpec(ops map[string]any, binding map[string]any) map[string]any {
	return map[string]any{
		"provider": map[string]any{"transport": "command", "operations": ops,
			"health": map[string]any{"call": "version"}},
		"provides": []any{binding},
	}
}

// A local program serves a capability like a web service does: an edit by
// copying the picture it is given, a picture generated by a program that
// writes one, the health check a free run, through the same contract check.
func TestALocalProgramServesACapability(t *testing.T) {
	commandWorld(t)
	img := pngBytes(t)
	install(t, "local-edit", commandSpec(
		map[string]any{"edit": map[string]any{"run": []any{"cp {image} {out.png}"}, "read": "file"},
			"version": map[string]any{"run": []any{"printf ok"}, "read": "text"}},
		map[string]any{"capability": "image.edit", "steps": []any{map[string]any{"call": "edit"}},
			"output": map[string]any{"image": map[string]any{"from": "body"}}}))
	reps, err := Test(context.Background(), "local-edit")
	if err != nil || len(reps) != 1 || !reps[0].OK {
		t.Fatalf("an edit by a local program: %+v %v", reps, err)
	}
	if h, err := CheckHealth(context.Background(), "local-edit"); err != nil || !h.OK {
		t.Errorf("health: %+v %v", h, err)
	}
	c, _ := GetConnector(RootDB, "local-edit")
	if sum := ConnectorSummary(c); !strings.Contains(sum, "runs cp, printf") || !strings.Contains(sum, "no network") {
		t.Errorf("an admin approving it is not shown what runs: %q", sum)
	}

	// A picture made from text: the program's output is the picture.
	b64 := base64.StdEncoding.EncodeToString(img)
	install(t, "local-gen", commandSpec(
		map[string]any{"gen": map[string]any{"run": []any{"printf %s " + b64, "base64 -d {in}"}, "read": "file"},
			"version": map[string]any{"run": []any{"printf ok"}, "read": "text"}},
		map[string]any{"capability": "image.generate", "steps": []any{map[string]any{"call": "gen"}},
			"output": map[string]any{"image": map[string]any{"from": "body"}}}))
	res, err := GenerateImageWithBackend(context.Background(), "local-gen", "a red circle", false)
	if err != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(res.URL); !bytes.Equal(got, img) {
		t.Error("the generated picture is not what the program wrote")
	}

	// A prompt cannot pose as an option to the program.
	install(t, "local-echo", commandSpec(
		map[string]any{"gen": map[string]any{"run": []any{"printf %s {prompt}"}, "read": "file"},
			"version": map[string]any{"run": []any{"printf ok"}, "read": "text"}},
		map[string]any{"capability": "image.generate", "steps": []any{map[string]any{"call": "gen"}},
			"output": map[string]any{"image": map[string]any{"from": "body"}}}))
	if _, err := Call(context.Background(), nil, "local-echo", "image.generate", map[string]any{"prompt": "--help"}); err == nil || !strings.Contains(err.Error(), "as an option") {
		t.Errorf("a prompt posing as an option: %v", err)
	}
}

// A command service has run lines and nothing of a web service's.
func TestACommandServiceIsOnlyRunLines(t *testing.T) {
	base := func() map[string]any {
		return commandSpec(map[string]any{"edit": map[string]any{"run": []any{"cp {image} {out.png}"}, "read": "file"},
			"version": map[string]any{"run": []any{"printf ok"}, "read": "text"}},
			map[string]any{"capability": "image.edit", "steps": []any{map[string]any{"call": "edit"}},
				"output": map[string]any{"image": map[string]any{"from": "body"}}})
	}
	if _, err := specFrom(t, base()); err != nil {
		t.Fatalf("a valid command service: %v", err)
	}
	for name, edit := range map[string]func(map[string]any){
		"an address":       func(m map[string]any) { provider(m)["base_url"] = "https://x.test" },
		"a credential":     func(m map[string]any) { provider(m)["auth"] = map[string]any{"credential": "k"} },
		"a path":           func(m map[string]any) { op(m, "edit")["path"] = "/x" },
		"no run lines":     func(m map[string]any) { delete(op(m, "edit"), "run") },
		"several results":  func(m map[string]any) { op(m, "edit")["run"] = []any{"cp {image} {outdir}"} },
		"an unknown token": func(m map[string]any) { op(m, "edit")["run"] = []any{"cp {photo} {out.png}"} },
	} {
		m := base()
		edit(m)
		if _, err := specFrom(t, m); err == nil {
			t.Errorf("a command service with %s passed", name)
		}
	}
}
